"""Корень репозитория и путь до пакета — на все команды в этом каталоге.

Скрипты запускают из склонированного репозитория, без установки пакета:
`python3 scripts/harvest.py --build`. Значит, каждой команде нужно самой
показать питону, где лежит `histctx`. Пятнадцать команд — пятнадцать
одинаковых пар строк с `sys.path.insert`, а следом `# noqa: E402` на каждом
импорте пакета, потому что перед импортами стояло выполняемое действие.

Теперь это действие одно и названо по имени:

    from _paths import ROOT      # заодно ставит src в sys.path

Импорт этого модуля меняет `sys.path` — то есть работает не только своим
значением, но и побочным действием; ради того он и заведён. Тестам путь
задан отдельно, в `pyproject.toml` (`pythonpath`), — оттуда же берётся и
сам этот модуль, когда тест грузит команду по пути.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

_SRC = str(ROOT / "src")
if _SRC not in sys.path:
    sys.path.insert(0, _SRC)
