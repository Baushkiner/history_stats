# --- названия районов --------------------------------------------------------

# Число в конце названия — расстояние до райцентра; номер после «№» — нет.
_RE_DISTANCE_TAIL = re.compile(r"(?<!№)(?<!№\s)\s*\d+(?:[.,]\d+)?\s*(?:км\.?)?\s*$", re.I)
# Приставка города или посёлка — только с точкой или пробелом после неё:
# иначе «Горьковская» и «Сузак» потеряли бы первую букву.
_RE_CITY = re.compile(r"^(?:город|гор|г)(?:\.\s*|\s+)(?=[А-ЯЁа-яё])", re.I)
_RE_SETTLEMENT = re.compile(r"^(пос|рп|с|п)(?:\.\s*|\s+)(?=[А-ЯЁа-яё])", re.I)
_RE_RN = re.compile(r"\b[Рр]-н\b\.?")
_ADJECTIVE = ("ий", "ый", "ой")
_ABBREVIATIONS = ((" АО", " автономная область"), (" авт. обл.", " автономная область"),
                  (" ЕАО", " (Еврейская автономная область)"))


def _with_unit(text: str, unit: str) -> str:
    """«Винницкий (рц в г. Виннице)» → «Винницкий район (рц в г. Виннице)»."""
    head, sep, tail = text.partition(" (")
    return f"{head} {unit}" + (f" ({tail}" if sep else "")


def raion_title(raw) -> Optional[str]:
    """Название района из листа — к виду «Бескарагайский район», «г. Павлодар».

    Число в конце — это расстояние от комендатуры до райцентра, которое
    набиравшие слили с названием («Бескарагайский 210 км»), — оно снимается.
    Слово-единица дописывается к прилагательному; оборванное «-ски» и «-ски й»
    дописываются до «-ский». Исходное написание остаётся в `extra`.
    """
    text = clean_text(raw)
    if not text:
        return None
    text = text.strip(" -,")
    stripped = _RE_DISTANCE_TAIL.sub("", text).strip(" -,")
    if not any(ch.isalpha() for ch in stripped):
        return None
    text = stripped
    text = re.sub(r"(\w)\s+(ий|й)$", r"\1\2", text)          # «Осински й», «Палкинск ий»
    text = re.sub(r"(ск)и$", r"\1ий", text)                   # «Ребрихински»
    text = _RE_RN.sub("район", text)
    text = re.sub(r"\bРайон\b", "район", text)
    for short, full in _ABBREVIATIONS:
        if text.endswith(short):
            text = text[: -len(short)] + full
    city = _RE_CITY.match(text)
    if city:
        rest = text[city.end():].strip()
        return "г. " + rest[:1].upper() + rest[1:]
    settlement = _RE_SETTLEMENT.match(text)
    if settlement:
        prefix = settlement.group(1).lower()
        prefix = {"пос": "пос.", "п": "пос.", "с": "с.", "рп": "рп"}.get(prefix, prefix)
        rest = text[settlement.end():].strip()
        return f"{prefix} {rest[:1].upper()}{rest[1:]}"
    if "район" in text or "автономная область" in text:
        return text
    if text.startswith(("им.", "имени")):
        return f"район {text}"
    if text.split(" (")[0].endswith(_ADJECTIVE):
        return _with_unit(text, "район")
    return text


def unit_kind(title: Optional[str]) -> str:
    """Город, посёлок или район — по началу названия; нужно, чтобы город и
    одноимённый район («г. Павлодар» и «Павлодарский район») не слились."""
    if not title:
        return "?"
    if title.startswith("г. "):
        return "город"
    if title.startswith(("пос. ", "рп ", "с. ")):
        return "посёлок"
    return "район"


_RE_STEM_PREFIX = re.compile(r"^(?:город|гор|г|пос|п|рп|с|пгт|им)(?:\.\s*|\s+)")
_RE_STEM_NOISE = re.compile(
    r"\b(?:район|р-н|гс|горсовет|авт\.?\s*обл\.?|нац\.?\s*окр\.?|ао|окр)\b\.?")


def name_stem(raw) -> str:
    """Основа названия для сверки: «г Троицк» и «Троицкий» дают одно и то же."""
    text = (clean_text(raw) or "").lower().replace("ё", "е")
    number = re.search(r"№\s*(\d+)", text)          # «Комендатура № 2» и «№ 3» — разные
    text = re.sub(r"\(.*?\)", " ", text)
    text = _RE_DISTANCE_TAIL.sub("", text)
    text = _RE_STEM_NOISE.sub(" ", text).strip()
    text = _RE_STEM_PREFIX.sub("", text).strip()
    text = re.sub(r"[^а-яa-z]+", "", text)
    text = re.sub(r"(?:ск|цк)?(?:ий|ый|ой|ая|ое|ие|ые|и)$", "", text)
    text = re.sub(r"(?:ск|цк|к)$", "", text)
    text = re.sub(r"[аяоеыиьй]+$", "", text)
    return text + (number.group(1) if number and text else "")


def similar_names(a, b) -> bool:
    """Названия одного района: основы равны или отличаются опечаткой."""
    sa, sb = name_stem(a), name_stem(b)
    if not sa or not sb:
        return False
    if sa == sb:
        return True
    if sa[-1].isdigit() or sb[-1].isdigit():         # номер комендатуры — только точно
        return False
    return min(len(sa), len(sb)) >= 5 and SequenceMatcher(None, sa, sb).ratio() >= 0.85


