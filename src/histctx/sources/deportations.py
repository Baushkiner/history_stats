def _count(value) -> int:
    if value is None:
        return 0
    if isinstance(value, float) and math.isnan(value):
        return 0
    return int(round(value))


def contingents(row: dict, columns: Iterable[str], labels: dict) -> dict[str, int]:
    """Ненулевые категории строки: подпись → число людей, по убыванию."""
    out: Counter = Counter()
    for column in columns:
        value = _count(row.get(column))
        if value:
            out[labels.get(column, column)] += value
    return dict(sorted(out.items(), key=lambda kv: (-kv[1], kv[0])))


# --- числа словами ----------------------------------------------------------

def thousands(value) -> str:
    # Неразрывный пробел в разряде тысяч: число не рвётся переносом строки.
    return f"{int(round(value)):,}".replace(",", " ")


def _plural(value, one: str, few: str, many: str) -> str:
    n = abs(int(round(value)))
    if 11 <= n % 100 <= 19:
        return many
    last = n % 10
    if last == 1:
        return one
    return few if 2 <= last <= 4 else many


def people(value) -> str:
    return f"{thousands(value)} {_plural(value, 'человек', 'человека', 'человек')}"


def settlers_word(value) -> str:
    return _plural(value, "спецпоселенец", "спецпоселенца", "спецпоселенцев")


def share(part: float, total: float) -> str:
    """Доля в процентах, как в census_1926_raion: «87%», «6,9%», «0,4%»."""
    percent = 100.0 * part / total
    shown = f"{percent:.1f}".rstrip("0").rstrip(".") if percent < 10 else f"{percent:.0f}"
    return f"{shown.replace('.', ',')}%"


def top_listing(counts: dict[str, int], n: int = 3) -> str:
    """«немцы — 1 988, калмыки — 635» по убыванию."""
    items = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:n]
    return ", ".join(f"{label} — {thousands(value)}" for label, value in items)


# --- точка и губерния -------------------------------------------------------

def point_of(lat, lon) -> tuple[Optional[float], Optional[float]]:
    if not valid_coords(lat, lon):
        return None, None
    return round(float(lat), 6), round(float(lon), 6)


def _confidence(lat, lon) -> str:
    if lat is None:
        return CONFIDENCE_NO_COORDS
    return CONFIDENCE_CENTROID if in_bbox(lat, lon) else CONFIDENCE_OUTSIDE


def _province(provinces, lat, lon) -> Optional[str]:
    if provinces is None or lat is None:
        return None
    return provinces.region_for(lat, lon)


def _place(district: Optional[str], region: Optional[str], republic: Optional[str]) -> str:
    parts = [district or "район не назван", region]
    if republic and republic != region:
        parts.append(republic)
    return ", ".join(p for p in parts if p)


