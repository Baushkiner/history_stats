def groups_1946(rows: Iterable[dict]) -> list[Group1946]:
    """Строки по районам: один `id_distr` — один район, кроме оговорённых номеров."""
    groups: dict[str, Group1946] = {}
    for index, row in enumerate(rows):
        ident = row.get("id_distr")
        if ident is None or _count(ident) in DISTINCT_IDS_1946:
            key = f"row{index}"
        else:
            key = str(_count(ident))
        groups.setdefault(key, Group1946(key, [])).rows.append(row)
    return list(groups.values())


def _label_1946(column: str, region: Optional[str], republic: str) -> str:
    if column == "othersum":
        return OTHER_1946.get(region or "", OTHER_1946.get(republic, "прочие"))
    return CONTINGENTS_1946.get(column, column)


def counts_1946(rows: list[dict], region: Optional[str], republic: str) -> dict[str, int]:
    out: Counter = Counter()
    for row in rows:
        for column, value in row.items():
            if not column.endswith("sum"):
                continue
            number = _count(value)
            if number:
                out[_label_1946(column, region, republic)] += number
    return dict(sorted(out.items(), key=lambda kv: (-kv[1], kv[0])))


def summary_1946(counts: dict[str, int], year_lead: str, same: list[str],
                 district: Optional[str] = None) -> str:
    where, what = _where(district)
    total = sum(counts.values())
    if not total:
        text = f"{year_lead}: {what} есть в таблице, но спецпоселенцев не учтено."
    else:
        head = f"{year_lead} {where} учтено {thousands(total)} {settlers_word(total)}"
        if len(counts) == 1:
            text = f"{head}: все — {next(iter(counts))}."
        else:
            text = f"{head}; больше всего: {top_listing(counts)}."
    if same:
        text += (f" Тот же район записан в таблице ещё строкой {', '.join(same)}: числа не "
                 "сложены — это могут быть разные комендатуры или разные документы.")
    return text


