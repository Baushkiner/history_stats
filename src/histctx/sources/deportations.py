def link_sets(rec_1951: list[ContextRecord], rec_1946: list[ContextRecord]) -> int:
    """Лист «Алтай 1946» из набора 1951 года и таблица 1946 года говорят об одних
    районах по разным документам, и числа у них разные. Записи одного района
    получают ссылки друг на друга; сложения нет. Возвращает число ссылок."""
    def key(rec):
        stem = name_stem(rec.district)
        return (rec.region, unit_kind(rec.district), stem) if stem else None

    by_key: dict[tuple, list[ContextRecord]] = defaultdict(list)
    for rec in rec_1946:
        if key(rec):
            by_key[key(rec)].append(rec)
    links = 0
    for rec in rec_1951:
        if rec.year_from != 1946 or not key(rec):
            continue
        for other in by_key.get(key(rec), []):
            rec.extra.setdefault("same_raion_other_set", []).append(other.source_id)
            other.extra.setdefault("same_raion_other_set", []).append(rec.source_id)
            links += 1
        if rec.extra.get("same_raion_other_set"):
            rec.summary += (" Тот же район есть и в таблице 1946 года (" +
                            ", ".join(rec.extra["same_raion_other_set"]) +
                            ") — по другому документу, числа не сложены.")
    return links


