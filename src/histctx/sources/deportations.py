def authors_sums_1946(rows_1946: list[dict], rows_1951: list[dict]) -> dict[str, tuple[int, int]]:
    """Суммы 1946 года по шагам `1a_create_deport_check_data.do` — с его ошибками.

    1. Строки одного `id_distr` складываются, а затем удаляются все копии
       (`drop if dup_id > 0`), а не лишние: район, записанный двумя строками,
       из таблицы выпадает целиком.
    2. Координаты районов 339 и 876 стираются, у 874 — только широта; строки с
       одинаковой точкой складываются и снова удаляются все копии
       (`drop if dup_coord > 0`): из сверки уходят все комендатуры, у которых
       точка общая с другой строкой, — а это обычно райцентр.
    3. В сумме «мусульман» `karachisum` стоит дважды: карачаевцы считаются
       два раза.
    """
    engl_of = _engl_map(rows_1951)
    rows = [dict(r) for r in rows_1946]
    ids = Counter(_count(r.get("id_distr")) for r in rows if r.get("id_distr") is not None)
    kept = [r for r in rows if r.get("id_distr") is None
            or _count(r.get("id_distr")) in DISTINCT_IDS_1946
            or ids[_count(r.get("id_distr"))] == 1]
    for row in kept:
        ident = _count(row.get("id_distr")) if row.get("id_distr") is not None else None
        if ident in (339, 876):
            row["latitude"] = row["longitude"] = None
        elif ident == 874:
            row["latitude"] = None
    coords = Counter((r.get("latitude"), r.get("longitude")) for r in kept
                     if r.get("latitude") is not None and r.get("longitude") is not None)
    kept = [r for r in kept if r.get("latitude") is None or r.get("longitude") is None
            or coords[(r.get("latitude"), r.get("longitude"))] == 1]
    out: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for row in kept:
        raw = clean_text(row.get("oblast")) or ""
        ident = _count(row.get("id_distr")) if row.get("id_distr") is not None else None
        if ident in AUTHORS_1946_IDS:
            engl = AUTHORS_1946_IDS[ident]
        elif raw in AUTHORS_1946_RAW:
            engl = AUTHORS_1946_RAW[raw]
        else:
            engl = engl_of.get(oblast_name(raw, OBLASTS_1946) or "")
        if not engl:
            continue
        out[engl][0] += _sum([row], PROT_1946)
        out[engl][1] += _sum([row], MUSLIM_1946) + _sum([row], ("karachisum",))
    return {k: (v[0], v[1]) for k, v in out.items()}


