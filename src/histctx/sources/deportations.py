def oblast_check(rows_1951: list[dict], rows_1946: list[dict],
                 compare: list[dict]) -> dict:
    """Сверка с таблицей областей авторов: что сходится и почему расходится."""
    a51 = authors_sums_1951(rows_1951)
    a46 = authors_sums_1946(rows_1946, rows_1951)
    o46 = our_sums_1946(rows_1946, rows_1951)
    rows = []
    for item in compare:
        engl = clean_text(item.get("oblast_engl")) or ""
        rows.append({
            "oblast_engl": engl,
            "table_1951": (_thousand_back(item.get("prot_000")),
                           _thousand_back(item.get("muslim_000"))),
            "authors_1951": a51.get(engl, (0, 0)),
            "table_1946": (_plain_int(item.get("prot1946")), _plain_int(item.get("muslim1946"))),
            "authors_1946": a46.get(engl, (0, 0)),
            "ours_1946": o46.get(engl, (0, 0)),
        })
    with_1946 = [r for r in rows if r["table_1946"][0] is not None]
    return {
        "rows": rows,
        "exact_1951": sum(r["table_1951"] == r["authors_1951"] for r in rows),
        "exact_1946": sum(r["table_1946"] == r["authors_1946"] for r in with_1946),
        "with_1946": len(with_1946),
        "no_1946_in_table": [r["oblast_engl"] for r in rows if r["table_1946"][0] is None],
        "ours_differ_1946": [r for r in with_1946 if r["ours_1946"] != r["table_1946"]],
        "not_in_table_1946": {k: v for k, v in o46.items()
                              if k not in {r["oblast_engl"] for r in rows}},
    }


def _thousand_back(value) -> Optional[int]:
    """Тысячи из float32 таблицы обратно в людей: 67.551003 → 67551."""
    if value is None:
        return None
    return int(round(float(value) * 1000))


def _plain_int(value) -> Optional[int]:
    if value is None:
        return None
    return int(round(float(value)))


