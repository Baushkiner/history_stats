def plain(value):
    """Число numpy/pandas → int или float Python, NaN → None, строка → чистая строка."""
    if value is None:
        return None
    if hasattr(value, "item"):
        value = value.item()
    if isinstance(value, float):
        if math.isnan(value):
            return None
        if value.is_integer() and abs(value) < 2 ** 53:
            return int(value)
        return float(f"{value:.7g}")
    if isinstance(value, str):
        return clean_text(value)
    return value


def read_dta(data: bytes, *, labels: bool = False) -> list[dict]:
    """`.dta` → строки-словари. `labels` раскрывает коды значений по меткам Stata:
    в сведении авторов номер строки переписи лежит кодом с меткой «CA4187»."""
    import pandas as pd

    try:
        frame = pd.read_stata(io.BytesIO(data), convert_categoricals=labels)
    except ValueError as exc:
        raise DeportationsError(f"таблица Stata не читается: {exc}") from exc
    columns = [str(c) for c in frame.columns]
    return [{c: plain(v) for c, v in zip(columns, row)}
            for row in frame.itertuples(index=False, name=None)]


