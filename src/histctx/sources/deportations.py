# --- Zenodo: перечень, оглавление, файлы ------------------------------------

def fetch_manifest(*, timeout: int = 60) -> list[dict]:
    """Перечень файлов записи: имя, размер, сумма."""
    raw = fetch_bytes(FILES_API, error=DeportationsError, timeout=timeout)
    try:
        entries = json.loads(raw)["entries"]
    except (ValueError, KeyError, TypeError) as exc:
        raise DeportationsError(f"ответ Zenodo не разбирается: {exc}") from exc
    return [{"key": e.get("key"), "size": e.get("size"), "checksum": e.get("checksum")}
            for e in entries]


def check_manifest(manifest: Iterable[dict]) -> list[str]:
    """Расхождения перечня с кодом; пусто — всё сходится."""
    by_key = {m.get("key"): m for m in manifest}
    got = by_key.get(ARCHIVE_KEY)
    if got is None:
        return [f"{ARCHIVE_KEY}: в записи такого файла нет; есть: "
                + ", ".join(sorted(str(k) for k in by_key))]
    problems = []
    if got.get("size") != ARCHIVE_SIZE:
        problems.append(f"размер {got.get('size')}, ожидался {ARCHIVE_SIZE}")
    if got.get("checksum") != f"md5:{ARCHIVE_MD5}":
        problems.append(f"сумма {got.get('checksum')}, ожидалась md5:{ARCHIVE_MD5}")
    return problems


def open_archive(*, url: str = ARCHIVE_URL, timeout: int = 300) -> zipfile.ZipFile:
    """Архив записи, открытый для чтения кусками по Range: один запрос к хвосту."""
    try:
        return zipfile.ZipFile(RangeFile(url, error=DeportationsError, chunk=RANGE_CHUNK,
                                         tail=1 << 18, timeout=timeout))
    except zipfile.BadZipFile as exc:
        raise DeportationsError(f"{url}: архив не разбирается как zip ({exc})") from exc


def listing(archive: zipfile.ZipFile) -> list[dict]:
    """Оглавление архива: путь от корня (без служебного `__MACOSX`), размер, CRC32."""
    out = []
    for info in archive.infolist():
        name = info.filename
        if name.startswith("__MACOSX/") or name.endswith("/"):
            continue
        if name.startswith(ARCHIVE_ROOT):
            name = name[len(ARCHIVE_ROOT):]
        out.append({"path": name, "size": info.file_size, "crc": info.CRC,
                    "compressed": info.compress_size, "zip_name": info.filename})
    return out


