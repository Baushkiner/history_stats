def _where(district: Optional[str]) -> tuple[str, str]:
    """(«в городе», «город») или («в районе», «район») — для описания записи."""
    if unit_kind(district) == "город":
        return "в городе", "город"
    if unit_kind(district) == "посёлок":
        return "в посёлке", "посёлок"
    return "в районе", "район"


def summary_1951(counts: dict[str, int], total: int, lead: str,
                 district: Optional[str] = None) -> str:
    where, what = _where(district)
    if not total:
        return (f"{lead}: {what} есть в листах, но спецпоселенцев не учтено "
                "(в наборе — ноль).")
    head = f"{lead} {where} учтено {thousands(total)} {settlers_word(total)}"
    if len(counts) == 1:
        label = next(iter(counts))
        return f"{head}: все — {label}."
    return f"{head}; больше всего: {top_listing(counts)}."


