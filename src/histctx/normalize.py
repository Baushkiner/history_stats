"""Приведение к единому виду свободнотекстовых значений из исходных файлов."""

from __future__ import annotations

import re
from typing import Optional

from .schema import clean_text

# Жанры в исходном файле записаны как попало: с запятыми, пояснениями в
# скобках, в единственном и множественном числе. Для фильтра на карте нужен
# короткий закрытый список.
_GENRE_RULES = (
    ("этнограф", "этнография"),
    ("путев", "путевые заметки"),
    ("воспомин", "воспоминания"),
    ("мемуар", "воспоминания"),
    ("автобиограф", "воспоминания"),
    ("дневник", "дневник"),
    ("письм", "письма"),
    ("очерк", "очерки"),
    ("публицист", "очерки"),
    ("фельетон", "очерки"),
    ("репортаж", "очерки"),
    ("роман", "роман"),
    ("сага", "роман"),
    ("эпопе", "роман"),
    ("повест", "повесть"),
    ("расска", "рассказы"),
    ("сказ", "рассказы"),
    ("детектив", "проза"),
    ("хроник", "хроника"),
    ("стих", "поэзия"),
    ("поэм", "поэзия"),
)

# В файле сражений одна и та же война записана по-разному: «Великая
# Отечественная война» и «Великая Отечественная война 1941–1945» — это 202 и
# 251 строка, которые на карте выглядят как два разных конфликта.
_WAR_CANON = (
    (r"велик\w*\s+отечествен", "Великая Отечественная война 1941–1945"),
    (r"перв\w*\s+миров", "Первая мировая война 1914–1918"),
    (r"втор\w*\s+миров|^вмв$", "Вторая мировая война 1939–1945"),
    (r"гражданск\w*\s+войн\w*\s+в\s+росс", "Гражданская война в России 1917–1922"),
    (r"отечествен\w*\s+войн\w*\s+1812", "Отечественная война 1812 года"),
    (r"северн\w*\s+войн", "Северная война 1700–1721"),
    (r"крымск\w*\s+войн", "Крымская война 1853–1856"),
    (r"кавказск\w*\s+войн", "Кавказская война 1817–1864"),
    (r"семилетн\w*\s+войн", "Семилетняя война 1756–1763"),
    (r"ливонск\w*\s+войн", "Ливонская война 1558–1583"),
    (r"смутн\w*\s+врем", "Смутное время 1598–1613"),
    (r"польск\w*\s+восстани\w*.*186|186.*польск\w*\s+восстани", "Польское восстание 1863–1864"),
    (r"польск\w*\s+восстани\w*.*183|183.*польск\w*\s+восстани", "Польское восстание 1830–1831"),
    (r"советско-польск", "Советско-польская война 1919–1921"),
    (r"советско-финл|зимн\w*\s+войн", "Советско-финляндская война 1939–1940"),
    (r"советско-японск", "Советско-японская война 1945"),
)

# Строки, которые описывают воинскую часть или корабль, а не событие на
# местности. На карте сражений им не место: у полка нет одной точки и одной даты.
_RE_UNIT = re.compile(
    r"(?:^|\s|«)(?:\d+-[йяе]\s+)?(?:гвардейск\w*\s+)?"
    r"(?:стрелков\w*|танков\w*|пехотн\w*|мотострелков\w*|кавалерийск\w*|воздушн\w*|"
    r"артиллерийск\w*|миномётн\w*|минометн\w*|самоходн\w*)?\s*"
    r"(?:дивизи\w*|полк\b|полка\b|бригад\w*|арми\w*|корпус\w*|батальон\w*|флотили\w*|эскадр\w*)",
    re.IGNORECASE,
)
_RE_SHIP = re.compile(
    r"\((?:канонерская лодка|крейсер|линкор|броненосец|миноносец|подводная лодка)\)",
    re.IGNORECASE)
_RE_EVENT = re.compile(
    r"(бой|бои|битв|сражени|осад|штурм|оборон|операци|десант|рейд|поход|прорыв|наступлени|"
    r"контрудар|восстани|мятеж|блокад|взяти|разгром|засад|налёт|налет|бомбардиров|экспедици|"
    r"вторжени|захват|нападени|манёвр|манев|отступлени|форсировани|капитуляци|стычк|дело при|"
    r"перестрелк|высадк|прорыв|окружени|котёл|котел)", re.IGNORECASE,
)


def normalize_genre(value: Optional[str]) -> Optional[str]:
    """«повесть (хотя в издательстве…)» -> «повесть»."""
    s = clean_text(value)
    if not s:
        return None
    # Пояснение в скобках может назвать чужой жанр («повесть (…автофикшен-романа)»),
    # поэтому сопоставляем только по основной части строки.
    head = re.split(r"[(,]", s)[0].strip()
    low = (head or s).lower()
    for needle, canon in _GENRE_RULES:
        if needle in low:
            return canon
    return head.lower() or None


def normalize_war(value: Optional[str]) -> Optional[str]:
    """Сводит разные написания одной войны к одному имени."""
    s = clean_text(value)
    if not s:
        return None
    low = s.lower().replace("ё", "е")
    for pattern, canon in _WAR_CANON:
        if re.search(pattern.replace("ё", "е"), low):
            return canon
    return s


def looks_like_military_unit(title: Optional[str]) -> bool:
    """Название описывает часть или корабль, а не событие."""
    s = clean_text(title)
    if not s:
        return False
    if _RE_SHIP.search(s):
        return True
    if _RE_EVENT.search(s):
        return False
    return bool(_RE_UNIT.search(s))


# Персоналии в списке сражений: «Петлюра, Симон Васильевич». Это биография,
# а не событие на местности, и на карту сражений она попадать не должна.
_RE_PERSON = re.compile(
    r"^[А-ЯЁ][а-яё\-]+,\s+[А-ЯЁ][а-яё]+(?:\s+[А-ЯЁ][а-яё]+(?:ич|вна|чна|ична|ыч))?\s*$"
)

# Год или диапазон в скобках: «Осада Смоленска (1613—1617)».
_RE_TITLE_YEARS = re.compile(r"\((\d{3,4})(?:\s*[—–\-]\s*(\d{3,4}))?\)")


def looks_like_person(title: Optional[str]) -> bool:
    """Название — это ФИО, а не событие."""
    s = clean_text(title)
    return bool(s and _RE_PERSON.match(s))


def years_from_title(title: Optional[str]) -> tuple[Optional[int], Optional[int]]:
    """Достаёт год из названия, когда колонка года пуста.

    В файле сражений так восстанавливается 151 датировка из 777 пропущенных.
    """
    s = clean_text(title)
    if not s:
        return None, None
    m = _RE_TITLE_YEARS.search(s)
    if not m:
        return None, None
    a = int(m.group(1))
    b = int(m.group(2)) if m.group(2) else a
    if not (1000 <= a <= 2100 and 1000 <= b <= 2100) or b < a:
        return None, None
    return a, b


def strip_quotes(value: Optional[str]) -> Optional[str]:
    """Убирает обрамляющие кавычки и лишние пробелы у названий произведений."""
    s = clean_text(value)
    if not s:
        return None
    s = s.strip().strip('"«»').strip()
    return s or None


def to_int(value) -> Optional[int]:
    """Целое из ячейки или None, если это не целое.

    Строго: «1937.0» — не год, а признак того, что колонку читают не так.
    Там, где источник и правда шлёт дробные целые, берут `to_int_loose`.
    """
    try:
        return int(str(value).strip())
    except (TypeError, ValueError):
        return None


def to_int_loose(value) -> Optional[int]:
    """Целое из ячейки, где источник пишет его дробным: «1899.0» — это 1899.

    Так приходят год и месяц в метеорядах и опорный срез в таблицах ERRHS.
    Строгий `to_int` потерял бы там всю таблицу, но и подменять его этим
    разбором нельзя: в остальных колонках дробное целое — признак того, что
    читают не ту колонку, и молчать об этом не следует.
    """
    try:
        return int(float(str(value).strip()))
    except (TypeError, ValueError):
        return None


def to_float(value) -> Optional[float]:
    """Число из ячейки или None. Пропуски, помеченные в источнике особым
    значением, отсеивает сам источник: что считать пропуском, знает только он."""
    try:
        return float(str(value).strip())
    except (TypeError, ValueError):
        return None


def tidy_url(value: Optional[str]) -> Optional[str]:
    s = clean_text(value)
    if not s:
        return None
    s = s.split()[0].strip().rstrip(",;")
    return s if s.lower().startswith(("http://", "https://")) else None
